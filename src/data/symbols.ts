export function isVisibleOnTimeframeGroup(
  vis: TimeframeVisibility | undefined,
  group: TimeframeGroup
): boolean {
  if (!vis) return true;
  if (group === 'Seconds') return vis.seconds;
  if (group === 'Minutes') return vis.minutes;
  if (group === 'Hours') return vis.hours;
  return vis.days;
}

